def ask_kpix(df, question):

    question = question.lower().strip()

    anomalies = df[df["is_anomaly"] == 1].copy()

    if anomalies.empty:
        return "KPIX did not detect any significant business anomalies."

    # ==========================================================
    # 1. HOW MANY ANOMALIES?
    # ==========================================================

    if "how many" in question and "anomal" in question:

        return (
            f"KPIX detected {len(anomalies)} anomalous transactions "
            f"in the current dataset."
        )

    # ==========================================================
    # 2. MOST ANOMALIES BY REGION
    # ==========================================================

    elif (
        "region" in question
        and "most" in question
        and "anomal" in question
    ):

        region_counts = (
            anomalies.groupby("region")
            .size()
            .sort_values(ascending=False)
        )

        region = region_counts.index[0]
        count = region_counts.iloc[0]

        return (
            f"The {region} region has the highest number of detected "
            f"anomalies, with {count} anomalous transactions."
        )

    # ==========================================================
    # 3. MOST ANOMALIES BY CATEGORY
    # ==========================================================

    elif (
        "category" in question
        and "most" in question
        and "anomal" in question
    ):

        category_counts = (
            anomalies.groupby("category")
            .size()
            .sort_values(ascending=False)
        )

        category = category_counts.index[0]
        count = category_counts.iloc[0]

        return (
            f"The {category} category has the highest number of detected "
            f"anomalies, with {count} anomalous transactions."
        )

    # ==========================================================
    # 4. MOST ANOMALIES BY PRODUCT
    # ==========================================================

    elif (
        "product" in question
        and "most" in question
        and "anomal" in question
    ):

        product_counts = (
            anomalies.groupby("product")
            .size()
            .sort_values(ascending=False)
        )

        product = product_counts.index[0]
        count = product_counts.iloc[0]

        return (
            f"The {product} product has the highest number of detected "
            f"anomalies, with {count} anomalous transactions."
        )

    # ==========================================================
    # 5. HIGHEST ANOMALY REVENUE
    # ==========================================================

    elif (
        "revenue" in question
        and "highest" in question
    ):

        top = anomalies.sort_values(
            "revenue",
            ascending=False
        ).iloc[0]

        return (
            f"The highest anomaly revenue is {top['revenue']:.2f}, "
            f"generated by {top['product']} in the "
            f"{top['region']} region."
        )

    # ==========================================================
    # 6. WHICH PRODUCT SHOULD MANAGEMENT INVESTIGATE?
    # ==========================================================

    elif (
        "which product" in question
        and (
            "investigate" in question
            or "management" in question
            or "look into" in question
            or "prioritize" in question
        )
    ):

        product_analysis = (
            anomalies.groupby("product")
            .agg(
                anomaly_count=("revenue", "count"),
                anomaly_revenue=("revenue", "sum"),
                average_revenue=("revenue", "mean")
            )
            .sort_values(
                "anomaly_revenue",
                ascending=False
            )
        )

        product = product_analysis.index[0]
        count = int(product_analysis.iloc[0]["anomaly_count"])
        revenue = product_analysis.iloc[0]["anomaly_revenue"]

        return (
            f"Management should investigate {product} first. "
            f"It has {count} detected anomalies with combined anomaly "
            f"revenue of {revenue:.2f}. This makes it one of the "
            f"highest-impact products in the current dataset."
        )

    # ==========================================================
    # 7. WHAT SHOULD THE BUSINESS DO ABOUT THE ANOMALIES?
    # ==========================================================

    elif (
        "what should" in question
        or "what can the business do" in question
        or "what action" in question
        or "what should the business" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        high_impact_count = len(
            anomalies[anomalies["impact_score"] >= 70]
        )

        return (
            f"The business should first investigate the highest-impact "
            f"anomalies, especially the {top['product']} transaction "
            f"in the {top['region']} region with revenue of "
            f"{top['revenue']:.2f}. KPIX identified "
            f"{high_impact_count} anomalies with an impact score of "
            f"70 or higher. Management should review pricing, quantity, "
            f"transaction details, and data quality before taking "
            f"corrective action."
        )

    # ==========================================================
    # 8. WHY IS A REGION UNDERPERFORMING?
    # ==========================================================

    elif (
        "why is" in question
        and (
            "performing poorly" in question
            or "performing bad" in question
            or "doing poorly" in question
            or "underperforming" in question
        )
    ):

        regions = df["region"].dropna().unique()

        selected_region = None

        for region in regions:
            if region.lower() in question:
                selected_region = region
                break

        # If no region is mentioned, use the region
        # with the lowest total revenue.

        if selected_region is None:

            region_revenue = (
                df.groupby("region")["revenue"]
                .sum()
                .sort_values()
            )

            selected_region = region_revenue.index[0]

        region_data = df[
            df["region"] == selected_region
        ]

        region_anomalies = anomalies[
            anomalies["region"] == selected_region
        ]

        region_revenue = region_data["revenue"].sum()

        anomaly_count = len(region_anomalies)

        anomaly_revenue = region_anomalies["revenue"].sum()

        average_revenue = region_data["revenue"].mean()

        top_product = (
            region_anomalies.groupby("product")["revenue"]
            .sum()
            .sort_values(ascending=False)
        )

        if not top_product.empty:
            main_product = top_product.index[0]
        else:
            main_product = "No specific product"

        return (
            f"The {selected_region} region may require attention because "
            f"it generated total revenue of {region_revenue:.2f} and "
            f"contains {anomaly_count} detected anomalies with combined "
            f"anomaly revenue of {anomaly_revenue:.2f}. "
            f"The average transaction revenue in this region is "
            f"{average_revenue:.2f}. "
            f"The product contributing the most anomaly revenue in this "
            f"region is {main_product}. "
            f"These figures indicate where management should investigate "
            f"further, but they do not establish the exact cause."
        )

    # ==========================================================
    # 9. WHAT COULD BE CAUSING THE REVENUE ANOMALY?
    # ==========================================================

    elif (
        "what could be causing" in question
        or "cause the revenue anomaly" in question
        or "causing the revenue anomaly" in question
        or "why is there a revenue anomaly" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        product = top["product"]
        region = top["region"]
        category = top["category"]
        revenue = top["revenue"]
        quantity = top["quantity"]
        unit_price = top["unit_price"]

        return (
            f"The strongest revenue anomaly involves {product} in the "
            f"{category} category in the {region} region, with revenue "
            f"of {revenue:.2f}. The transaction has a quantity of "
            f"{quantity} and a unit price of {unit_price:.2f}. "
            f"Possible areas to investigate include unusual pricing, "
            f"unusually large quantities, exceptional customer orders, "
            f"or data-entry issues. KPIX cannot determine the exact "
            f"cause from the available sales data alone."
        )

    # ==========================================================
    # 10. WHICH REGION SHOULD MANAGEMENT INVESTIGATE?
    # ==========================================================

    elif (
        "which region" in question
        and (
            "investigate" in question
            or "management" in question
            or "look into" in question
            or "prioritize" in question
            or "attention" in question
        )
    ):

        region_analysis = (
            anomalies.groupby("region")
            .agg(
                anomaly_count=("revenue", "count"),
                anomaly_revenue=("revenue", "sum")
            )
            .sort_values(
                "anomaly_revenue",
                ascending=False
            )
        )

        region = region_analysis.index[0]
        count = int(region_analysis.iloc[0]["anomaly_count"])
        revenue = region_analysis.iloc[0]["anomaly_revenue"]

        return (
            f"Management should investigate the {region} region first. "
            f"It has {count} detected anomalies with combined anomaly "
            f"revenue of {revenue:.2f}, making it the highest anomaly-"
            f"revenue region in the current dataset."
        )

    # ==========================================================
    # 11. WHICH CATEGORY SHOULD MANAGEMENT INVESTIGATE?
    # ==========================================================

    elif (
        "which category" in question
        and (
            "investigate" in question
            or "management" in question
            or "look into" in question
            or "prioritize" in question
        )
    ):

        category_analysis = (
            anomalies.groupby("category")
            .agg(
                anomaly_count=("revenue", "count"),
                anomaly_revenue=("revenue", "sum")
            )
            .sort_values(
                "anomaly_revenue",
                ascending=False
            )
        )

        category = category_analysis.index[0]
        count = int(category_analysis.iloc[0]["anomaly_count"])
        revenue = category_analysis.iloc[0]["anomaly_revenue"]

        return (
            f"Management should investigate the {category} category "
            f"first. It contains {count} detected anomalies with "
            f"combined anomaly revenue of {revenue:.2f}."
        )

    # ==========================================================
    # 12. HIGHEST IMPACT ANOMALY
    # ==========================================================

    elif (
        "highest impact" in question
        or "most important anomaly" in question
        or "biggest anomaly" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        return (
            f"The highest-impact anomaly involves {top['product']} "
            f"in the {top['region']} region. Its revenue is "
            f"{top['revenue']:.2f} and its impact score is "
            f"{top['impact_score']:.2f}. This should be one of "
            f"the first transactions reviewed by management."
        )

    # ==========================================================
    # 13. WHICH CATEGORY CONTRIBUTES MOST TO ANOMALY REVENUE?
    # ==========================================================

    elif (
        "category" in question
        and (
            "anomaly revenue" in question
            or "revenue" in question
        )
        and (
            "contribute" in question
            or "contributing" in question
        )
    ):

        category_revenue = (
            anomalies.groupby("category")["revenue"]
            .sum()
            .sort_values(ascending=False)
        )

        category = category_revenue.index[0]
        revenue = category_revenue.iloc[0]

        return (
            f"The {category} category contributes the most anomaly "
            f"revenue, with a combined value of {revenue:.2f}."
        )

    # ==========================================================
    # 14. WHICH PRODUCT GENERATES MOST ANOMALY REVENUE?
    # ==========================================================

    elif (
        "product" in question
        and "anomaly revenue" in question
    ):

        product_revenue = (
            anomalies.groupby("product")["revenue"]
            .sum()
            .sort_values(ascending=False)
        )

        product = product_revenue.index[0]
        revenue = product_revenue.iloc[0]

        return (
            f"The {product} product generates the highest anomaly "
            f"revenue, with a combined anomaly revenue of {revenue:.2f}."
        )

    # ==========================================================
    # 15. WHICH REGION HAS HIGHEST ANOMALY REVENUE?
    # ==========================================================

    elif (
        "region" in question
        and "anomaly revenue" in question
    ):

        region_revenue = (
            anomalies.groupby("region")["revenue"]
            .sum()
            .sort_values(ascending=False)
        )

        region = region_revenue.index[0]
        revenue = region_revenue.iloc[0]

        return (
            f"The {region} region has the highest anomaly revenue, "
            f"with a combined value of {revenue:.2f}."
        )

    # ==========================================================
    # 16. WHAT FACTORS MAY BE CONTRIBUTING TO THE ANOMALIES?
    # ==========================================================

    elif (
        "what factors" in question
        or "factors may be contributing" in question
        or "factors are contributing" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        return (
            f"KPIX found that the highest-impact anomaly involves "
            f"{top['product']} in the {top['region']} region. "
            f"Important factors to investigate include the transaction "
            f"quantity of {top['quantity']}, unit price of "
            f"{top['unit_price']:.2f}, product-level activity, regional "
            f"patterns, and possible data-quality issues. These are "
            f"investigation areas rather than confirmed causes."
        )

    # ==========================================================
    # 17. WHAT IS THE BIGGEST BUSINESS RISK?
    # ==========================================================

    elif (
        "biggest business risk" in question
        or "greatest business risk" in question
        or "biggest risk" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        return (
            f"The biggest potential business risk identified by KPIX is "
            f"the high-impact {top['product']} anomaly in the "
            f"{top['region']} region. It generated revenue of "
            f"{top['revenue']:.2f} with an impact score of "
            f"{top['impact_score']:.2f}. Management should verify "
            f"whether this represents a genuine business event or "
            f"an abnormal transaction."
        )

    # ==========================================================
    # 18. WHERE SHOULD MANAGEMENT FOCUS?
    # ==========================================================

    elif (
        "where should management focus" in question
        or "where should management" in question
        or "where should the business focus" in question
    ):

        region = (
            anomalies.groupby("region")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        product = (
            anomalies.groupby("product")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        category = (
            anomalies.groupby("category")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        return (
            f"Management should focus first on the {region} region, "
            f"the {product} product, and the {category} category. "
            f"These areas currently contribute the largest portions "
            f"of detected anomaly revenue and therefore deserve "
            f"further investigation."
        )

    # ==========================================================
    # 19. WHAT IS THE MOST IMPORTANT BUSINESS FINDING?
    # ==========================================================

    elif (
        "most important business finding" in question
        or "most important finding" in question
        or "key business finding" in question
    ):

        top = anomalies.sort_values(
            "impact_score",
            ascending=False
        ).iloc[0]

        region_count = len(
            anomalies[anomalies["region"] == top["region"]]
        )

        return (
            f"The most important finding is a high-impact anomaly "
            f"involving {top['product']} in the {top['region']} region. "
            f"The transaction generated revenue of {top['revenue']:.2f} "
            f"with an impact score of {top['impact_score']:.2f}. "
            f"The {top['region']} region also contains "
            f"{region_count} detected anomalies, making it an important "
            f"area for management to investigate."
        )

    # ==========================================================
    # 20. EXECUTIVE SUMMARY
    # ==========================================================

    elif (
        "summarize" in question
        or "summary" in question
        or "what should management know" in question
    ):

        total_anomalies = len(anomalies)

        total_anomaly_revenue = anomalies["revenue"].sum()

        top_region = (
            anomalies.groupby("region")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        top_product = (
            anomalies.groupby("product")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        top_category = (
            anomalies.groupby("category")["revenue"]
            .sum()
            .sort_values(ascending=False)
            .index[0]
        )

        return (
            f"KPIX detected {total_anomalies} anomalous transactions "
            f"with combined anomaly revenue of "
            f"{total_anomaly_revenue:.2f}. The {top_region} region "
            f"has the highest anomaly revenue, while {top_product} "
            f"is the leading product and {top_category} is the "
            f"leading category by anomaly revenue. Management should "
            f"investigate these areas first and verify whether the "
            f"detected patterns represent genuine business events "
            f"or unusual transactions."
        )

    # ==========================================================
    # 21. DEFAULT RESPONSE
    # ==========================================================

    else:

        return (
            "I can answer business questions about anomaly patterns, "
            "regions, categories, products, revenue, business risks, "
            "possible causes, management actions, and recommended "
            "areas for investigation."
        )